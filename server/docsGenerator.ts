import type { NexoraProject } from '../src/types/nexora.ts';
import { DEFAULT_USER_ID, dbAppendProjectHistory, dbGetProject, dbUpsertProject } from './database.ts';
import { writeWorkspaceFilesToDisk } from './projectEngine.ts';

export function generateProjectDocumentation(
  projectId: string,
  ownerId = DEFAULT_USER_ID
): { project: NexoraProject; readmeMarkdown: string } {
  const project = dbGetProject(projectId, ownerId);
  if (!project) throw new Error('Project not found.');

  const routes: string[] = [];
  for (const file of project.files) {
    if (file.path.endsWith('.js') || file.path.endsWith('.ts')) {
      const matches = file.content.matchAll(/(?:app\.(?:get|post|put|patch|delete)\(|url\.pathname\s*(?:===|\.startsWith\()\s*)['"`]([^'"`]+)['"`]/g);
      for (const m of matches) {
        if (m[1]) routes.push(m[1]);
      }
    }
  }
  const uniqueRoutes = Array.from(new Set(routes));

  const pkgFile = project.files.find((f) => f.path === 'package.json');
  let dependenciesList = 'None (Zero external runtime dependencies)';
  if (pkgFile) {
    try {
      const pkg = JSON.parse(pkgFile.content) as { dependencies?: Record<string, string> };
      const entries = Object.entries(pkg.dependencies || {});
      if (entries.length > 0) {
        dependenciesList = entries.map(([k, v]) => `- \`${k}\`: \`${v}\``).join('\n');
      }
    } catch {
      dependenciesList = 'Unable to parse package.json';
    }
  }

  const runInstructions =
    project.type === 'website'
      ? project.files.some((f) => f.path === 'server.js')
        ? '1. Click **Start Backend Server** inside Nexora Workspace or run `node server.js` locally.\n2. Open the Live Preview panel or inspect routes via the Testing Center.'
        : '1. Open `index.html` in the Live Preview panel or export the static ZIP bundle.'
      : '1. Export the complete Android source ZIP from the Export Center.\n2. Open the extracted folder in Android Studio or run `./gradlew assembleDebug` with JDK 17+ and Android SDK 35 installed.';

  const readmeMarkdown = `# ${project.name}

> Generated by Nexora Studio · Project ID: \`${project.id}\`

## Overview
${project.prompt}

- **Project Type**: \`${project.type}\`${project.gameGenre ? ` (${project.gameGenre})` : ''}
- **Created**: ${new Date(project.createdAt).toLocaleString()}
- **Latest Build Status**: \`${project.build.status}\`
- **APK Binary Present**: ${project.build.apkAvailable ? 'Yes (`' + project.build.apkFilename + '`)' : 'No'}

## Architecture & File Inventory (${project.files.length} files)
${project.files.map((f) => `- \`${f.path}\` (${f.language})`).join('\n')}

## Dependencies
${dependenciesList}

${
  uniqueRoutes.length > 0
    ? `## Detected Backend API Endpoints\n${uniqueRoutes.map((r) => `- \`${r}\``).join('\n')}\n`
    : ''
}${
    project.envVars && project.envVars.length > 0
      ? `## Environment Variables\n${project.envVars.map((e) => `- \`${e.key}\``).join('\n')}\n`
      : ''
  }
## Setup & Running
${runInstructions}

## Limitations & Toolchain Notes
${
  project.type === 'website'
    ? '- Isolated Node runner executes in a sandboxed child process without host Nexora Studio secrets.'
    : '- APK compilation requires local or remote JDK + Gradle + Android SDK (`ANDROID_HOME`). In-browser preview renders a simulated mobile or HTML5 game view.'
}
`;

  const nextFiles = [...project.files];
  const readmeIdx = nextFiles.findIndex((f) => f.path === 'README.md');
  if (readmeIdx >= 0) {
    nextFiles[readmeIdx] = { path: 'README.md', language: 'markdown', content: readmeMarkdown };
  } else {
    nextFiles.unshift({ path: 'README.md', language: 'markdown', content: readmeMarkdown });
  }

  const updated = dbUpsertProject({
    ...project,
    files: nextFiles,
  });
  writeWorkspaceFilesToDisk(updated);

  const finalProj =
    dbAppendProjectHistory(
      projectId,
      'docs_generated',
      `Updated README.md inspecting ${project.files.length} project files.`,
      ownerId
    ) || updated;

  return { project: finalProj, readmeMarkdown };
}
